export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocale] = useState<Locale>(() => {
    if (typeof window === 'undefined') return 'nl'
    const stored = window.localStorage.getItem('radio-locale')
    if (stored === 'nl' || stored === 'en' || stored === 'de' || stored === 'fr') return stored
    const lang = navigator.language.slice(0, 2)
    if (lang === 'en') return 'en'
    if (lang === 'de') return 'de'
    if (lang === 'fr') return 'fr'
    return 'nl'
  })

  const handleSetLocale = useCallback((l: Locale) => {
    setLocale(l)
    window.localStorage.setItem('radio-locale', l)
    document.documentElement.lang = l
  }, [])

  const t = useCallback(
    (key: string, vars?: Record<string, string>) => {
      let value = translations[locale][key] ?? translations.nl[key] ?? key
      if (vars) {
        for (const [k, v] of Object.entries(vars)) {
          value = value.replace(`{${k}}`, v)
        }
      }
      return value
    },
    [locale],
  )

  const value = useMemo(() => ({ locale, setLocale: handleSetLocale, t }), [locale, handleSetLocale, t])

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}
